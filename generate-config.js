// generate-config.js
// Script đọc file .env và tự động cập nhật vào js/config.js khi kéo source về máy khác
const fs = require('fs');
const path = require('path');

const envPath = path.join(__dirname, '.env');
const configJsPath = path.join(__dirname, 'js', 'config.js');

if (!fs.existsSync(envPath)) {
    console.log('[Notice] Không tìm thấy file .env, tạo file .env từ .env.example...');
    const examplePath = path.join(__dirname, '.env.example');
    if (fs.existsSync(examplePath)) {
        fs.copyFileSync(examplePath, envPath);
    }
}

let envContent = '';
if (fs.existsSync(envPath)) {
    envContent = fs.readFileSync(envPath, 'utf8');
}

const parseEnv = (content) => {
    const env = {};
    content.split('\n').forEach(line => {
        const trimmed = line.trim();
        if (trimmed && !trimmed.startsWith('#')) {
            const idx = trimmed.indexOf('=');
            if (idx > -1) {
                const key = trimmed.substring(0, idx).trim();
                const val = trimmed.substring(idx + 1).trim();
                env[key] = val;
            }
        }
    });
    return env;
};

const envVars = parseEnv(envContent);
const supabaseUrl = envVars.SUPABASE_URL || 'https://qdkhqvsbtmbgkmoldazt.supabase.co';
const supabaseKey = envVars.SUPABASE_ANON_KEY || 'sb_publishable_HNBq9BOkrn7bmJxsG4ZHbQ_p937j35i';
const phone = envVars.CONTACT_PHONE || '0367020403';
const zalo = envVars.CONTACT_ZALO || 'https://zalo.me/0367020403';
const email = envVars.CONTACT_EMAIL || 'voviet4323@gmail.com';
const facebook = envVars.CONTACT_FACEBOOK || 'https://www.facebook.com/quocviet43';

const newConfigContent = `// js/config.js
// Cấu hình kết nối Supabase và Thông tin liên hệ
// Tự động sinh từ file .env (Auto-generated by generate-config.js)

const SUPABASE_CONFIG = {
    url: '${supabaseUrl}',
    anonKey: '${supabaseKey}'
};

const CONTACT_INFO = {
    phone: '${phone}',
    zalo: '${zalo}',
    email: '${email}',
    facebook: '${facebook}'
};

// Khởi tạo Supabase client
let supabaseClient = null;
if (typeof supabase !== 'undefined' && SUPABASE_CONFIG.url && SUPABASE_CONFIG.url.indexOf('YOUR_PROJECT_ID') === -1) {
    try {
        supabaseClient = supabase.createClient(SUPABASE_CONFIG.url, SUPABASE_CONFIG.anonKey);
    } catch (e) {
        console.warn('Không thể khởi tạo Supabase Client:', e);
    }
}

// Export cấu hình ra window
window.APP_CONFIG = {
    supabaseConfig: SUPABASE_CONFIG,
    contactInfo: CONTACT_INFO,
    getClient: () => supabaseClient
};
`;

fs.writeFileSync(configJsPath, newConfigContent, 'utf8');
console.log('✅ Đã đồng bộ cấu hình từ .env vào js/config.js thành công!');

